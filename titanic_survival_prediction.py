import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
sns.set_style('darkgrid')

data = pd.read_csv('Titanic-Dataset.csv')

data

data.describe(include='all')

data.isnull()

data.isnull().sum()

data = data.dropna(axis=0)

data

data.isnull().sum()

data.Cabin.unique()

data.Ticket.unique()

data.PassengerId.unique()

data.Name.unique()

data.drop(columns=['Name','Cabin','PassengerId','Ticket'],inplace=True)

data

data['Sex'] = data['Sex'].map({'male':1,'female':0})

data

data['Embarked'] = data['Embarked'].map({'C':0,'Q':1,'S':2})

data

X = data.drop('Survived',axis=1)

X

y = data.Survived

y

from sklearn.model_selection import train_test_split

X_train,X_test,y_train,y_test = train_test_split(X,y,test_size=0.2,random_state=0)

X_train.shape

X_test.shape

from sklearn.linear_model import LogisticRegression

model = LogisticRegression()

model.fit(X_train,y_train)

y_test

y_pred = model.predict(X_test)

y_pred

from sklearn.metrics import confusion_matrix,classification_report,ConfusionMatrixDisplay

print(confusion_matrix(y_test,y_pred))

cm = confusion_matrix(y_test,y_pred)

cm

disp = ConfusionMatrixDisplay(confusion_matrix=cm,display_labels=model.classes_)
disp.plot()
plt.grid(False)
plt.show()

print(classification_report(y_test,y_pred))

def predict(Pclass,	Sex, Age, SibSp, Parch, Fare, Embarked):
    prediction = model.predict([[Pclass, Sex, Age, SibSp, Parch, Fare, Embarked]])[0]

    if prediction == 1:
        return "Passenger will survive ✅"
    else:
        return "Passenger will not survive ❌"

